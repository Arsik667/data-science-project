"""
Builds and executes notebooks/pipeline.ipynb: a walkthrough of the whole
pipeline (stages 1-7). The notebook runs the same scripts as the command line,
so it cannot drift from the .py files. Each stage writes its full log to
outputs/; the notebook then shows the key tables and figures.

Run:  .venv/bin/python src/build_notebook.py
"""
from pathlib import Path

import nbformat as nbf
from nbclient import NotebookClient

ROOT = Path(__file__).resolve().parents[1]
NB = ROOT / "notebooks" / "pipeline.ipynb"

cells = []


def md(text):
    cells.append(nbf.v4.new_markdown_cell(text.strip()))


def code(text):
    cells.append(nbf.v4.new_code_cell(text.strip()))


md("""
# Postcode-level estimation of school-run car use (Leeds) – pipeline walkthrough

Team 9 · client: Hastings Direct.

This notebook runs the whole analysis, stage by stage, with the same scripts as the command line (`src/*.py`). Each stage:

1. writes its outputs to `outputs/` and its figures to `figures/`;
2. writes its full printed log to `outputs/stageN_log.txt`;
3. shows its key results here.

**Rules followed throughout**

- The 2025 survey and the 2024 cut-off distances are **validation only**.
- Religion is never a predictor.
- Postcodes are strings, distances are in metres, and the school ID is `EstablishmentNumber`.
- All random seeds are 42.

*Generated by `src/build_notebook.py`; edit that file, not this notebook.*
""")

code("""
import contextlib, runpy, subprocess, sys
from pathlib import Path

import pandas as pd
from IPython.display import Image, Markdown, display

ROOT = Path.cwd().parent if Path.cwd().name == "notebooks" else Path.cwd()
OUT, FIG = ROOT / "outputs", ROOT / "figures"
sys.path.insert(0, str(ROOT / "src"))
pd.set_option("display.precision", 3)
pd.set_option("display.max_columns", 30)


def run_stage(script, log=None):
    \"\"\"Run src/<script> exactly as from the command line; save its printout.\"\"\"
    path = ROOT / "src" / script
    if log is None:
        with contextlib.redirect_stdout(None):
            runpy.run_path(str(path), run_name="__main__")
    else:
        with open(OUT / log, "w") as f, contextlib.redirect_stdout(f):
            runpy.run_path(str(path), run_name="__main__")
    print(f"ran {script}" + (f" -> outputs/{log}" if log else ""))


def show_log(log, start, n=15):
    \"\"\"Print n lines of a stage log, starting at the first line that contains `start`.\"\"\"
    lines = (OUT / log).read_text().splitlines()
    i = next(k for k, line in enumerate(lines) if start in line)
    print("\\n".join(lines[i:i + n]))
""")

# ---------------------------------------------------------------- stage 1
md("""
## Stage 1 – Data preparation → `postcodes_master.csv`

- **Primary age** means Reception to Year 6 on Census day: 1/12 of the 0–4 band, all of 5–9 and 19/60 of 10–14.
- **Car access** means 1 or more cars: `car_rate = 1 − no car / table total`.
- Each OA's children and households are split **equally** between its postcodes. Giving every postcode the full OA count would inflate the total about 8 times.
""")
code("""
run_stage("stage1_data_prep.py", "stage1_log.txt")
m = pd.read_csv(OUT / "postcodes_master.csv", dtype={"POSTCODE": str, "OA": str})
assert m["POSTCODE"].is_unique and m["POSTCODE"].notna().all()
print(f"{len(m):,} postcodes, {m.OA.nunique():,} OAs, {m.est_kids.sum():,.1f} primary-age children")
m.head()
""")
code('display(Image(FIG / "stage1_maps.png", width=900))')

# ---------------------------------------------------------------- stage 2
md("""
## Stage 2 – Distances and Method 1 (nearest school)

The distance matrix is straight-line metres from OS grid coordinates, computed with NumPy broadcasting (20,799 × 225). Method 1 sends every child to the nearest listed school.
""")
code("""
run_stage("stage2_distances_method1.py", "stage2_log.txt")
m1 = pd.read_csv(OUT / "method1_postcode.csv", dtype={"POSTCODE": str})
m1["dist_nearest_m"].describe(percentiles=[.5, .9]).round(0)
""")
code('display(Image(FIG / "stage2_map.png", width=700))')

# ---------------------------------------------------------------- stage 3
md("""
## Stage 3 – Method 2: probabilistic attendance and car use

P(j | i) ∝ capacity_j · B_j · exp(−d_ij / λ), with balancing factors B_j ≤ 1 that enforce school capacity. Then P(car | i, j) = car_rate_i · g(d_ij), where g is a logistic curve with d50 = 1,000 m fixed a priori.

λ is chosen on **input data only**: the value under which population and distance best reproduce the real school rolls. A 2-fold school split checks that the choice holds out of sample.
""")
code("""
run_stage("stage3_method2.py", "stage3_log.txt")
display(pd.read_csv(OUT / "method2_ladder.csv").drop(columns="note"))
show_log("stage3_log.txt", "=== Main model outputs", 7)
""")
code('display(Image(FIG / "stage3_map_car_rate.png", width=700))')

# ---------------------------------------------------------------- stage 4
md("""
## Stage 4 – Validation (survey and cut-off distances; never fed back)

Schools are matched to the survey by name in four steps: exact → normalised → fuzzy (score ≥ 95) → manual. The manual decisions are in `data/manual/manual_matches.csv`. The cut-off PDF is matched by DfE number.
""")
code("""
run_stage("school_matching.py", "matching_log.txt")
run_stage("stage4_validation.py", "stage4_log.txt")
pd.read_csv(OUT / "validation_metrics_survey.csv").query("subset == 'all compared'")
""")
code("""
display(pd.read_csv(OUT / "validation_metrics_cutoff.csv"))
display(Image(FIG / "stage4_survey_scatter.png", width=950))
""")

# ---------------------------------------------------------------- stage 5
md("""
## Stage 5 – Fairness audit

Protected characteristics are used only to **audit** the model. The religion-by-OA file was not provided, so that check is not run; its method is in `outputs/fairness_method.md`.
""")
code("""
run_stage("stage5_fairness.py", "stage5_log.txt")
display(pd.read_csv(OUT / "fairness_groups.csv")[["group", "n_schools", "obs_share", "pred_share",
                                                     "mean_error", "ci_low", "ci_high"]])
display(pd.read_csv(OUT / "fairness_regression.csv"))
display(Image(FIG / "stage5_error_by_group.png", width=950))
""")

# ---------------------------------------------------------------- stage 6
md("""
## Stage 6 – Sensitivity and uncertainty

The scenarios change one assumption at a time. A Monte Carlo run then draws λ, d50 and the g(d) scale jointly (200 draws, seed 42).
""")
code("""
run_stage("stage6_sensitivity.py", "stage6_log.txt")
display(pd.read_csv(OUT / "sensitivity_one_at_a_time.csv"))
show_log("stage6_log.txt", "=== B. Monte Carlo", 12)
""")
code('display(Image(FIG / "stage6_sensitivity.png", width=950))')

# ---------------------------------------------------------------- stage 7
md("""
## Stage 7 – Report built from code output

`report/report_draft.md` is filled from `report/report_template.md`. Every number is recomputed from `outputs/` and listed with its source in `outputs/report_numbers.csv`. The Word version is written by `src/export_docx.py`.
""")
code("""
run_stage("stage7_report.py", "stage7_log.txt")
run_stage("export_docx.py")
pd.read_csv(OUT / "report_numbers.csv").head(12)
""")

# ---------------------------------------------------------------- checks
md("""
## Quality checks

The test suite covers:

- unique postcode keys with no NaN;
- matching shapes;
- the total of `est_kids` against the school rolls;
- probability rows summing to at most 1;
- hand-checked toy examples;
- that every report number is traced to its source.
""")
code("""
r = subprocess.run([sys.executable, "-m", "pytest", "tests", "-q", "--color=no"], cwd=ROOT, capture_output=True, text=True)
print(r.stdout.strip().splitlines()[-1])
assert r.returncode == 0
""")

nb = nbf.v4.new_notebook(cells=cells, metadata={"kernelspec": {"name": "python3", "display_name": "Python 3",
                                                               "language": "python"}})


def main():
    NB.parent.mkdir(exist_ok=True)
    NotebookClient(nb, timeout=1800, kernel_name="python3",
                   resources={"metadata": {"path": str(NB.parent)}}).execute()
    nbf.write(nb, NB)
    print(f"executed and wrote {NB.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
